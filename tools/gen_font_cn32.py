
# gen_font_cn32.py -- render the Chinese glyphs the game HUD needs into a
# 32x32 bitmap table. The 16x16 table lost strokes on complex characters
# (环/绕/疗/屏...), which is why the HUD looked broken on the real screen.
# 32x32 is 128 bytes per glyph, ~12.5 KB for ~100 glyphs, which lives in
# .rodata (DDR) and costs nothing in BRAM.
import os
from PIL import Image, ImageDraw, ImageFont

WS = r'C:\Users\25437\Desktop\竞赛\嵌入式设计竞赛FPGA设计项目\2D图形加速引擎'
OUT = os.path.join(WS, 'work', 'gfx_demo', 'src', 'font_cn.h')
PREVIEW = os.path.join(WS, 'work', 'gfx_demo', 'assets-preview', 'font-cn32.png')

TEXT = ("时间击杀等级生命元素硬件软火力方向键移动暂停退出自攻击存按开始升选择确认"
        "速多重伤害环绕治疗磁铁飞刀游戏结束活波次分数帧率个同屏显示"
        "键本次得分最高记录秒球左右敌人弹幕波数清上下难度"
        "空格")

chars = []
for ch in TEXT:
    if ch not in chars:
        chars.append(ch)
print('chars:', len(chars))

# Uses only SIL OFL 1.1 licensed fonts (Noto Sans SC / Source Han Sans),
# so the rendered bitmap glyphs are redistributable.
cands = [r'C:\Windows\Fonts\Noto Sans SC (TrueType).otf',
         r'C:\Windows\Fonts\Noto Sans SC Medium (TrueType).otf',
         r'C:\Windows\Fonts\NotoSansSC-VF.ttf']
font_path = next((p for p in cands if os.path.exists(p)), None)
print('font:', font_path)
assert font_path

SZ = 32
# Find (size, y-offset) that keeps the glyph inside the box with the most ink.
best = None
for size in (32, 31, 30, 29, 28, 27, 26, 25, 24, 23, 22):
    for oy in (-4, -3, -2, -1, 0, 1, 2, 3, 4):
        f = ImageFont.truetype(font_path, size)
        total = 0
        ok = 0
        bms = []
        for ch in chars:
            im = Image.new('L', (SZ, SZ), 0)
            d = ImageDraw.Draw(im)
            d.text((0, oy), ch, font=f, fill=255)
            px = im.load()
            rows = []
            ink = 0
            edge = False
            for y in range(SZ):
                v = 0
                for x in range(SZ):
                    if px[x, y] > 70:
                        v |= (1 << (31 - x))
                        ink += 1
                        if x == 0 or x == SZ-1 or y == 0 or y == SZ-1:
                            edge = True
                rows.append(v)
            if edge:
                break
            bms.append(rows)
            total += ink
        else:
            if best is None or total > best[0]:
                best = (total, size, oy, bms)
        if best and best[1] == size and best[2] == oy:
            break

assert best, 'no size fits'
total, size, oy, bms = best
print('chosen size=%d oy=%d ink=%d' % (size, oy, total))

# pack: 4 bytes per row, bit7 of first byte = leftmost pixel
with open(OUT, 'w', encoding='utf-8', newline='\n') as fo:
    fo.write('// font_cn.h -- 32x32 bitmap glyphs for the Chinese HUD text (generated by\n')
    fo.write('// tools/gen_font_cn32.py from Noto Sans SC (SIL OFL 1.1).\n')
    fo.write('// 16x16 lost strokes on complex characters; 32x32 keeps them.\n')
    fo.write('// Each glyph is 128 bytes: 32 rows, four bytes per row, bit7 of the\n')
    fo.write('// first byte is the leftmost pixel.\n')
    fo.write('#ifndef FONT_CN_H\n#define FONT_CN_H\n#include <stdint.h>\n\n')
    fo.write('#define CN_N %d\n\n' % len(chars))
    fo.write('static const uint16_t CN_CP[CN_N] = {\n    ')
    fo.write(', '.join('0x%04X' % ord(c) for c in chars))
    fo.write('\n};\n\n')
    fo.write('static const uint8_t CN_BITS[CN_N][128] = {\n')
    for i, ch in enumerate(chars):
        fo.write('    { ')
        flat = []
        for row in bms[i]:
            flat += [(row >> 24) & 0xFF, (row >> 16) & 0xFF, (row >> 8) & 0xFF, row & 0xFF]
        fo.write(', '.join('0x%02X' % b for b in flat))
        fo.write(' },\n')
    fo.write('};\n\n#endif // FONT_CN_H\n')

# preview: draw all glyphs in a grid for eyeballing
cols = 16
rows_n = (len(chars) + cols - 1) // cols
img = Image.new('RGB', (cols * (SZ + 4), rows_n * (SZ + 4)), (20, 20, 30))
d = ImageDraw.Draw(img)
for i, ch in enumerate(chars):
    cx = (i % cols) * (SZ + 4)
    cy = (i // cols) * (SZ + 4)
    for y in range(SZ):
        for x in range(SZ):
            if bms[i][y] & (1 << (31 - x)):
                img.putpixel((cx + x, cy + y), (255, 255, 255))
d2 = ImageDraw.Draw(img)
img.save(PREVIEW)
print('wrote', OUT, 'and', PREVIEW, 'glyphs:', len(chars))