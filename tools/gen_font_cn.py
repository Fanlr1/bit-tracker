
# gen_font_cn.py -- render the handful of Chinese glyphs the game HUD needs into
# a 16x16 bitmap table, so the firmware can draw real Chinese text with the CPU.
import os
from PIL import Image, ImageDraw, ImageFont

WS = r'C:\Users\25437\Desktop\竞赛\嵌入式设计竞赛FPGA设计项目\2D图形加速引擎'
OUT = os.path.join(WS, 'work', 'gfx_demo', 'src', 'font_cn.h')
PREVIEW = os.path.join(WS, 'work', 'gfx_demo', 'assets-preview', 'font-cn.png')

TEXT = ("时间击杀等级生命元素硬件软火力方向键移动暂停退出自攻击存按开始升选择确认"
        "速多重伤害环绕治疗磁铁飞刀游戏结束活波次分数帧率个同屏显示范围缩短增加"
        "键继续重新设置当前目标本次得分最高记录秒球左右敌人弹幕波数清上下难度")

chars = []
for ch in TEXT:
    if ch not in chars:
        chars.append(ch)
print('chars:', len(chars))

# find a CJK font
# SIL OFL 1.1 licensed fonts only, so the bitmap glyphs are redistributable.
cands = [r'C:\Windows\Fonts\Noto Sans SC (TrueType).otf',
         r'C:\Windows\Fonts\NotoSansSC-VF.ttf']
font_path = next((p for p in cands if os.path.exists(p)), None)
print('font:', font_path)
assert font_path

BIT = None
SZ = 16
for size in (16, 15, 14):
    for oy in (-3, -2, -1, 0, 1):
        f = ImageFont.truetype(font_path, size)
        ok = 0
        bitmaps = []
        for ch in chars:
            im = Image.new('L', (SZ, SZ), 0)
            d = ImageDraw.Draw(im)
            d.text((0, oy), ch, font=f, fill=255)
            px = im.load()
            rows = []
            ink = 0
            for y in range(SZ):
                v = 0
                for x in range(SZ):
                    if px[x, y] >= 128:
                        v |= (1 << (15 - x))
                        ink += 1
                rows.append(v)
            # too little or too much ink means the glyph is clipped or bled
            if 6 <= ink <= 200:
                ok += 1
            bitmaps.append(rows)
        print('size', size, 'oy', oy, 'ok', ok, '/', len(chars))
        if ok >= len(chars) - 1:
            BIT = bitmaps
            break
    if BIT: break
assert BIT

lines = []
lines.append('// font_cn.h -- 16x16 bitmap glyphs for the Chinese HUD text (generated by')
lines.append('// tools/gen_font_cn.py from %s).' % os.path.basename(font_path))
lines.append('// Each glyph is 32 bytes: 16 rows, two bytes per row, bit15 = leftmost pixel.')
lines.append('#ifndef FONT_CN_H')
lines.append('#define FONT_CN_H')
lines.append('#include <stdint.h>')
lines.append('')
lines.append('#define CN_N %d' % len(chars))
lines.append('')
cps = ', '.join('0x%04X' % ord(c) for c in chars)
lines.append('static const uint16_t CN_CP[CN_N] = {')
lines.append('    ' + cps)
lines.append('};')
lines.append('')
lines.append('static const uint8_t CN_BITS[CN_N][32] = {')
for ch, rows in zip(chars, BIT):
    bs = []
    for r in rows:
        bs.append('0x%02X,0x%02X' % ((r >> 8) & 0xFF, r & 0xFF))
    lines.append('    { ' + ', '.join(bs) + ' },  // ' + ch)
lines.append('};')
lines.append('')
lines.append('#endif // FONT_CN_H')
lines.append('')
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print('wrote', OUT)

# preview: all glyphs at 4x with labels
SCALE = 4
cols = 12
rows_n = (len(chars) + cols - 1) // cols
cw = SZ * SCALE + 6
im = Image.new('RGB', (cols * cw, rows_n * (SZ * SCALE + 10) + 6), (18, 22, 34))
d = ImageDraw.Draw(im)
for i, (ch, rows) in enumerate(zip(chars, BIT)):
    ox = (i % cols) * cw + 3
    oy = (i // cols) * (SZ * SCALE + 10) + 3
    for y in range(SZ):
        for x in range(SZ):
            if rows[y] & (1 << (15 - x)):
                d.rectangle([ox + x * SCALE, oy + y * SCALE, ox + x * SCALE + SCALE - 1, oy + y * SCALE + SCALE - 1], fill=(220, 240, 255))
im.save(PREVIEW)
print('wrote', PREVIEW)